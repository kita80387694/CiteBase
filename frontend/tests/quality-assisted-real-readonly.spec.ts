import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('辅助续开发真实已保存评测：只读任务、引用与JSON下载', async ({ page }) => {
  const id = process.env.E2E_EVALUATION_ID;
  test.skip(!id, 'Requires saved real evaluation; never creates paid work');
  const writes: string[] = [];
  page.on('request', request => { if (request.method() !== 'GET' && request.method() !== 'OPTIONS' && !request.url().endsWith('/auth/login')) writes.push(request.url()); });
  await page.goto('/'); await page.getByRole('button', { name: '进入 CiteBase' }).click();
  await expect(page.locator('.mode')).toHaveText('real');
  const token = await page.evaluate(() => localStorage.getItem('citebase.token'));
  const headers = { Authorization: `Bearer ${token}` };
  const response = await page.request.get(`/api/evaluations/${id}`, { headers }); expect(response.ok()).toBe(true);
  const run = await response.json(); expect(run.taskStatus).toBe('SUCCEEDED'); expect(run.partial).toBe(false); expect(run.config.modelMode).toBe('real');
  const taskView = await (await page.request.get(`/api/tasks/${id}`, { headers })).json();
  await page.locator('#knowledge-base').selectOption(taskView.kbId);
  await page.getByRole('button', { name: '处理任务', exact: true }).click();
  const task = page.locator(`[data-task-id="${id}"]`); await expect(task.locator('.badge')).toHaveText('任务完成');
  expect(taskView.retryGeneration).toBe(0); await expect(task).toContainText('恢复代次 0'); await task.getByRole('button', { name: '任务详情', exact: true }).click();
  await expect(page.locator('.task-details')).toContainText('externalCalls');
  await page.screenshot({ path: '../docs/screenshots/quality-assisted-real-tasks-20261001.png', fullPage: true });
  await task.getByRole('button', { name: '打开结果', exact: true }).click();
  await expect(page.getByRole('heading', { name: run.name, exact: true })).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/quality-assisted-real-evaluation-20261001.png', fullPage: true });
  const dl = page.waitForEvent('download'); await page.getByRole('button', { name: '导出 JSON', exact: true }).click();
  const exported = JSON.parse(await readFile((await (await dl).path())!, 'utf8'));
  expect(exported.results).toEqual(run.results); expect(exported.pendingItems).toHaveLength(0);
  const row = run.results.find((r: any) => r.citations?.length);
  expect(row).toBeTruthy();
  await page.getByRole('button', { name: row.question, exact: true }).first().click();
  await page.locator('.drawer.wide .inline-citation').first().click();
  await expect(page.locator('.drawer .source-text')).not.toBeEmpty();
  await expect(page.locator('.drawer')).toContainText('本次评测快照版本');
  await page.screenshot({ path: '../docs/screenshots/quality-assisted-real-evaluation-citation-20261001.png' });
  expect(writes).toEqual([]);
});
